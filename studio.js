function loadSwiperAssets() {
  if (window.Swiper) return Promise.resolve(window.Swiper);
  if (swiperAssetsPromise) return swiperAssetsPromise;

  const cssPromise = new Promise((resolve) => {
    const existing = document.querySelector("[data-swiper-css]");
    if (existing) {
      resolve();
      return;
    }

    const stylesheet = document.createElement("link");
    stylesheet.rel = "stylesheet";
    stylesheet.href = SWIPER_CSS_HREF;
    stylesheet.dataset.swiperCss = "true";
    stylesheet.onload = resolve;
    stylesheet.onerror = resolve;
    document.head.appendChild(stylesheet);
  });

  const scriptPromise = new Promise((resolve, reject) => {
    const existing = document.querySelector("[data-swiper-script]");
    if (existing) {
      existing.addEventListener("load", () => resolve(window.Swiper), { once: true });
      existing.addEventListener("error", reject, { once: true });
      return;
    }

    const script = document.createElement("script");
    script.src = SWIPER_JS_SRC;
    script.async = true;
    script.dataset.swiperScript = "true";
    script.onload = () => resolve(window.Swiper);
    script.onerror = reject;
    document.body.appendChild(script);
  });

  swiperAssetsPromise = Promise.all([cssPromise, scriptPromise]).then(([, SwiperClass]) => SwiperClass);
  return swiperAssetsPromise;
}

function setupCaseSlider(root, ui) {
  const viewport = root.querySelector(".case-slider__viewport");
  const track = root.querySelector("[data-case-slider-track]");
  const counter = root.querySelector("[data-case-slider-counter]");
  const prevButton = root.querySelector("[data-case-slider-prev]");
  const nextButton = root.querySelector("[data-case-slider-next]");
  if (!viewport || !track || !counter || !prevButton || !nextButton) return;

  if (root._caseSliderAbort) root._caseSliderAbort.abort();
  const controller = new AbortController();
  root._caseSliderAbort = controller;
  const signal = controller.signal;

  const slides = [...track.querySelectorAll(".case-slider__slide")];
  if (!slides.length) return;

  const isFull = slides.some((slide) => slide.classList.contains("case-slider__slide--full"));
  let activeIndex = 0;

  function offsetForIndex(index) {
    const slide = slides[index];
    if (!slide) return 0;
    if (isFull) return index * viewport.clientWidth;
    return slide.offsetLeft - (viewport.clientWidth - slide.clientWidth) / 2;
  }

  function syncFullSlideWidths() {
    if (!isFull) return;
    const width = viewport.clientWidth;
    slides.forEach((slide) => {
      slide.style.flex = `0 0 ${width}px`;
      slide.style.width = `${width}px`;
    });
  }

  function renderSlider() {
    syncFullSlideWidths();
    track.style.transform = `translateX(${-offsetForIndex(activeIndex)}px)`;
    counter.textContent = `${activeIndex + 1} / ${slides.length}`;
    prevButton.disabled = activeIndex === 0;
    nextButton.disabled = activeIndex === slides.length - 1;
    prevButton.setAttribute("aria-label", ui.prev);
    nextButton.setAttribute("aria-label", ui.next);
  }

  prevButton.addEventListener(
    "click",
    () => {
      activeIndex = Math.max(0, activeIndex - 1);
      renderSlider();
    },
    { signal },
  );

  nextButton.addEventListener(
    "click",
    () => {
      activeIndex = Math.min(slides.length - 1, activeIndex + 1);
      renderSlider();
    },
    { signal },
  );

  if (slides.length > 1) {
    let pointerId = null;
    let startX = 0;
    let startY = 0;
    let startOffset = 0;
    let dragging = false;
    let axis = null;

    function stopDrag(event) {
      if (pointerId !== event.pointerId) return;
      const dx = event.clientX - startX;
      pointerId = null;
      viewport.classList.remove("is-dragging");
      if (!dragging) {
        axis = null;
        return;
      }
      dragging = false;
      axis = null;

      const visual = startOffset - dx;
      let nearest = activeIndex;
      let best = Infinity;
      slides.forEach((_, index) => {
        const distance = Math.abs(offsetForIndex(index) - visual);
        if (distance < best) {
          best = distance;
          nearest = index;
        }
      });
      if (nearest === activeIndex && Math.abs(dx) > 56) {
        nearest = dx < 0 ? Math.min(slides.length - 1, activeIndex + 1) : Math.max(0, activeIndex - 1);
      }
      activeIndex = nearest;
      renderSlider();
    }

    viewport.addEventListener(
      "pointerdown",
      (event) => {
        if (event.pointerType === "mouse" && event.button !== 0) return;
        pointerId = event.pointerId;
        startX = event.clientX;
        startY = event.clientY;
        startOffset = offsetForIndex(activeIndex);
        dragging = false;
        axis = null;
        viewport.setPointerCapture(event.pointerId);
      },
      { signal },
    );

    viewport.addEventListener(
      "pointermove",
      (event) => {
        if (pointerId !== event.pointerId) return;
        const dx = event.clientX - startX;
        const dy = event.clientY - startY;
        if (!axis) {
          if (Math.hypot(dx, dy) < 8) return;
          axis = Math.abs(dx) > Math.abs(dy) ? "x" : "y";
          if (axis === "x") {
            dragging = true;
            viewport.classList.add("is-dragging");
          }
        }
        if (axis !== "x") return;
        const first = offsetForIndex(0);
        const last = offsetForIndex(slides.length - 1);
        let next = startOffset - dx;
        if (next < first) next = first - (first - next) * 0.28;
        if (next > last) next = last + (next - last) * 0.28;
        track.style.transform = `translateX(${-next}px)`;
      },
      { signal },
    );

    viewport.addEventListener("pointerup", stopDrag, { signal });
    viewport.addEventListener("pointercancel", stopDrag, { signal });
    viewport.addEventListener("dragstart", (event) => event.preventDefault(), { signal });
  }

  window.addEventListener(
    "resize",
    () => {
      window.requestAnimationFrame(renderSlider);
    },
    { passive: true, signal },
  );

  renderSlider();
}

