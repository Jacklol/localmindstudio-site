function setupGallery() {
  const modal = document.querySelector("#screen-gallery");
  const modalTitle = document.querySelector("#gallery-title");
  const modalNote = document.querySelector("#gallery-note");
  const wrapper = document.querySelector("#gallery-wrapper");
  const closeButton = document.querySelector("[data-gallery-close]");
  let activeSwiper;

  if (!modal || !modalTitle || !modalNote || !wrapper || !closeButton) return;

  async function openGallery(key) {
    const gallery = galleries[key];
    if (!gallery) return;

    const translatedGallery = translations[currentLanguage].galleryCases[key];
    const translatedScreens = translations[currentLanguage].galleryScreens?.[key] || [];

    if (activeSwiper) {
      try {
        activeSwiper.destroy(true, true);
      } catch (error) {
        // Swiper can throw if slides were already removed from the DOM.
      }
      activeSwiper = null;
    }

    modalTitle.textContent = translatedGallery?.[0] || gallery.title;
    modalNote.textContent = translatedGallery?.[1] || gallery.note;
    wrapper.innerHTML = gallery.screens
      .map(([src, label, variant], index) => {
        const isWide = variant === "wide";
        const screenLabel = translatedScreens[index] || label;
        return `
          <div class="swiper-slide${isWide ? " wide-slide" : ""}">
            <figure class="screen-shot${isWide ? " screen-shot-wide" : ""}">
              <img src="${src}" alt="${screenLabel}" loading="${index < 2 ? "eager" : "lazy"}" decoding="async" />
              <figcaption>${screenLabel}</figcaption>
            </figure>
          </div>
        `;
      })
      .join("");

    setMenuOpen(false, true);
    lockScroll();
    if (typeof modal.showModal === "function") {
      modal.showModal();
    } else {
      modal.setAttribute("open", "");
    }

    const SwiperClass = await loadSwiperAssets().catch(() => null);
    if (SwiperClass) {
      activeSwiper = new SwiperClass(".gallery-swiper", {
        effect: "coverflow",
        grabCursor: true,
        centeredSlides: true,
        slidesPerView: "auto",
        spaceBetween: 20,
        keyboard: { enabled: true },
        pagination: { el: ".swiper-pagination", clickable: true },
        navigation: {
          nextEl: ".swiper-button-next",
          prevEl: ".swiper-button-prev",
        },
        coverflowEffect: {
          rotate: 0,
          stretch: 0,
          depth: 130,
          modifier: 1.1,
          slideShadows: false,
        },
      });
    }
  }

  function closeGallery() {
    if (activeSwiper) {
      try {
        activeSwiper.destroy(true, true);
      } catch (error) {
        // Ignore stale Swiper instances when the dialog closes.
      }
      activeSwiper = null;
    }
    modal.close?.();
    modal.removeAttribute("open");
    unlockScroll();
  }

  document.querySelector(".case-showcase")?.addEventListener("click", (event) => {
    const trigger = event.target.closest("[data-gallery]");
    if (!trigger) return;
    openGallery(trigger.dataset.gallery);
  });

  document.querySelector(".case-showcase")?.addEventListener("keydown", (event) => {
    if (event.key !== "Enter" && event.key !== " ") return;
    const trigger = event.target.closest("[data-gallery]");
    if (!trigger) return;
    event.preventDefault();
    openGallery(trigger.dataset.gallery);
  });

  closeButton.addEventListener("click", closeGallery);
  modal.addEventListener("close", unlockScroll);
  modal.addEventListener("click", (event) => {
    if (event.target === modal) closeGallery();
  });
}

